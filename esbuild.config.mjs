import esbuildSvelte from 'esbuild-svelte';
import { sveltePreprocess } from 'svelte-preprocess';
import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	plugins: [
		esbuildSvelte({
			compilerOptions: {
				css: 'injected',
				// Using a custom content-based hash in order to allow for
				// CSS hot-reloading in Obsidian. The filename is included
				// such that components with identical style blocks don't
				// share a hash.
				cssHash: ({ css, filename, hash }) =>
					`oab-${hash(filename + css)}`,
			},
			preprocess: sveltePreprocess(),
			// Ignore compiler warnings from third-party .svelte sources (e.g. bits-ui)
			filterWarnings: (warning) =>
				!warning.filename?.includes('node_modules'),
		}),
	],
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	define: {},
	conditions: ['svelte', 'browser'],
	mainFields: ['svelte', 'browser', 'module', 'main'],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
